const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1100, height: 700 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.setContent('<body class="page-log"><div id="app"></div></body>');
    for (const file of ['common.css', 'log.css']) await page.addStyleTag({ content: fs.readFileSync(path.join(__dirname, '../media', file), 'utf8') });
    await page.evaluate(() => {
      window.sent = [];
      window.acquireVsCodeApi = () => ({ getState: () => ({}), setState: () => {}, postMessage: m => window.sent.push(m) });
    });
    for (const file of ['common.js', 'graph.js', 'log.js']) await page.addScriptTag({ content: fs.readFileSync(path.join(__dirname, '../media', file), 'utf8') });
    const send = data => page.evaluate(data => window.dispatchEvent(new MessageEvent('message', { data })), data);
    await send({ type: 'init', part: 'commits', mode: 'main' });
    await send({ type: 'filter', repo: '/work', repoName: 'All repositories', paths: 'All repositories', graphLayout: 'compact', order: 'date' });
    const commits = [...Array.from({ length: 35 }, (_, i) => ({ h: `tip${i}`, p: [`parent${i}`], repo: `/work/repo${i}`, ae: 'a@b', an: 'Author', at: 200, s: `Tip ${i}` })), ...Array.from({ length: 35 }, (_, i) => ({ h: `parent${i}`, p: [], repo: `/work/repo${i}`, ae: 'a@b', an: 'Author', at: 100, s: `Parent ${i}` }))];
    await send({ type: 'log', commits, graph: true, head: 'tip0', me: '' });
    await send({ type: 'branches', current: 'main', head: 'tip0', local: [{ name: 'main', hash: 'tip0' }, { name: 'armin-dev', hash: 'tip1' }], remote: [], tags: [] });
    await page.getByRole('button', { name: 'Branch', exact: true }).click();
    await page.getByRole('menuitemradio', { name: 'armin-dev', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'branchFilter', ref: 'armin-dev' });
    await page.getByRole('button', { name: 'Date', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Last 7 days', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'setDate', since: '7 days ago', label: 'Last 7 days' });
    await page.getByRole('button', { name: 'User', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Author <a@b>', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'setAuthors', authors: [{ label: 'Author', pattern: 'a@b' }] });
    await page.getByRole('button', { name: 'Options', exact: true }).click();
    assert.equal(await page.getByRole('menu').count(), 1, 'Options must open inside the Git view');
    await send({ type: 'filter', repo: '/work', repoName: 'All repositories', paths: 'All repositories', graphLayout: 'compact', order: 'date' });
    assert.equal(await page.getByRole('menu').count(), 1, 'unchanged background refresh must not dismiss an open dropdown');
    await page.getByRole('menuitemradio', { name: 'Topologically', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'setLogOptions', order: 'topo' });
    await page.getByRole('button', { name: 'Options', exact: true }).click();
    await page.getByRole('menuitemcheckbox', { name: 'First Parent', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'setLogOptions', firstParent: true });
    await page.getByRole('button', { name: 'Options', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Rebuild selected histories', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'rebuildHistory' });
    assert.ok(await page.locator('.commit-row').first().locator('svg.graph').evaluate(el => el.getBoundingClientRect().width) < 80, '35 unrelated histories must not create a rainbow wall');
    await page.locator('.commit-row').first().locator('svg.graph').click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'focusRepository', repo: '/work/repo0' });
    await page.getByRole('button', { name: 'Paths: All repositories', exact: true }).click();
    await send({ type: 'menuData', what: 'paths', items: [{ label: 'repo0', value: '/work/repo0', checked: true }, { label: 'repo1', value: '/work/repo1', checked: true }] });
    await page.getByRole('checkbox', { name: 'All repositories', exact: true }).uncheck();
    await page.getByRole('checkbox', { name: 'repo1', exact: true }).check();
    await page.getByRole('button', { name: 'Apply', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.sent.at(-1)), { type: 'setRepositories', repositories: ['/work/repo1'] });
    await send({ type: 'log', commits, graph: true, graphLayout: 'lanes', head: 'tip0', me: '' });
    assert.ok(await page.locator('.commit-row').first().locator('svg.graph').evaluate(el => el.getBoundingClientRect().width) > 100, 'All repository lanes is an explicit alternate layout');
    await send({ type: 'log', commits, graph: true, graphLayout: 'compact', head: 'tip0', me: '' });
    const many = Array.from({ length: 5000 }, (_, i) => ({ h: `c${i}`, p: i < 4999 ? [`c${i + 1}`] : [], repo: '/work/big', ae: 'a@b', an: 'Author', at: 10000 - i, s: `Commit ${i}` }));
    const renderMs = await page.evaluate(m => { const t = performance.now(); window.dispatchEvent(new MessageEvent('message', { data: m })); return performance.now() - t; }, { type: 'log', commits: many, graph: true, graphLayout: 'compact', head: 'c0', me: '' });
    assert.ok(await page.locator('.commit-row').count() < 200, 'large histories render only rows near the viewport');
    await page.locator('.commits').evaluate(box => { box.scrollTop = 4000 * 22; });
    await page.waitForFunction(() => document.querySelector('.commit-row[data-i="4000"]'));
    await page.evaluate(() => window.dispatchEvent(new MessageEvent('message', { data: { type: 'reveal', hash: 'c10' } })));
    await page.waitForFunction(() => document.querySelector('.commit-row.selected[data-i="10"]'));
    console.log(`5000-commit render ${renderMs.toFixed(0)}ms`);
    assert.deepEqual(errors, []);
    await page.screenshot({ path: path.join(__dirname, '../log-ui-verified.png') });
    console.log('PASS: real DOM dropdowns, option requests, compact 35-repository graph, clickable history focus, root multi-selection, no JS errors');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
